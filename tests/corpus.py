"""Measure unmodified example sources; execute only explicit smoke fixtures."""
import hashlib
import os
from pathlib import Path
import subprocess
import sys
import tempfile
from toolrun import runner

root = Path(__file__).resolve().parents[1]
exe = Path(os.environ.get('XLT88', root / 'xlt88'))
flavors = ('nasm', 'asm86', 'masm3', 'drasm86')
targets = ('msdos', 'cpm86')
# These are already 8086 output/reference sources, not translation inputs.
outputs = {'copy-dos.asm', 'copycpm.asm', 'test1.asm', 'test2.asm'}
readers = {'forth.asm': 'm80', 'wash15.asm': 'm80', 'disk7.mac': 'mac'}
smoke = {'hello.asm': b'Hello, world', 'tst8080.asm': b'CPU IS OPERATIONAL'}
report = ['# Example acceptance measurements', '',
          'Generated by `python3 tests/corpus.py corpus.md` from unmodified sources.',
          'Normalization includes reading and symbol construction; it does not prove mnemonic support.',
          'Translate/assemble counts cover four emitters × two OS targets. Only the two explicit smoke fixtures execute.', '',
          '| Source | SHA256 prefix | Reader | Normalize | Translate | Assemble | Execute |',
          '| --- | --- | --- | --- | --- | --- | --- |']
details = []
failed_smoke = False
with tempfile.TemporaryDirectory() as directory:
    work = Path(directory)
    for source in sorted(list((root / 'examples').glob('*.asm')) + list((root / 'examples').glob('*.mac'))):
        if source.name in outputs:
            continue
        dialect = readers.get(source.name, 'asm80')
        raw = source.read_bytes()
        result = subprocess.run([str(exe), '--dialect='+dialect, '--emit=asm80', str(source), str(work/'norm.asm')], capture_output=True, text=True)
        normalized = result.returncode == 0
        errors = []
        if not normalized:
            errors.append('Normalize: '+result.stderr.strip())
        translated = assembled = executed = 0
        for target in targets:
            _, build, execute = runner(work, target)
            for flavor in flavors:
                result = subprocess.run([str(exe), '--dialect='+dialect, '--target='+target, '--emit='+flavor, str(source), str(work/'check.asm')], capture_output=True, text=True)
                if result.returncode:
                    errors.append(f'{flavor}/{target}: '+ '\n'.join(result.stderr.splitlines()[:3]))
                    continue
                translated += 1
                try:
                    build('example', raw, flavor, dialect=dialect)
                    assembled += 1
                    if source.name in smoke:
                        assert smoke[source.name] in execute('example'), 'missing success marker'
                        executed += 1
                except Exception as error:
                    errors.append(f'{flavor}/{target}: {error}')
        if source.name in smoke and executed != 8:
            failed_smoke = True
        report.append(f'| {source.name} | {hashlib.sha256(raw).hexdigest()[:12]} | {dialect} | {"pass" if normalized else "blocked"} | {translated}/8 | {assembled}/8 | {str(executed)+"/8" if source.name in smoke else "not run"} |')
        details += ['', '## '+source.name] if errors else []
        if errors:
            details += ['', 'Observed blocker samples (at most three diagnostic lines per combination):']
            seen = set()
            for error in errors:
                diagnostic = error.split(': ', 1)[-1]
                if diagnostic not in seen:
                    seen.add(diagnostic)
                    details += ['', '```text', error[:1800], '```']
        print(f'{source.name}: normalize={normalized}, translate={translated}/8, assemble={assembled}/8, execute={executed}/8', flush=True)
report += ['', 'Excluded existing 8086 references: '+', '.join(sorted(outputs))+'.'] + details
if len(sys.argv) > 1:
    Path(sys.argv[1]).write_text('\n'.join(report)+'\n')
if failed_smoke:
    print('\n'.join(report))
    raise SystemExit('An established smoke fixture regressed')
